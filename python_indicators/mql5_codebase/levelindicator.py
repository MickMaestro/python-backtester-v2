def OnCalculate(rates_total, prev_calculated, time, open, high, low, close, tick_volume, volume, spread):
    global _s_OnCalculate_time_, _s_OnCalculate_triggered
    if (not alert) and (not notification):
        return rates_total
    if equal(lv.Price_1(0), close[rates_total - 1], deviation * SymbolInfoDouble(None, SYMBOL_POINT)):
        if _s_OnCalculate_time_ != time[rates_total - 1]:
            _s_OnCalculate_time_ = time[rates_total - 1]
        else:
            return rates_total
        if not _s_OnCalculate_triggered:
            if alert:
                Alert('Level Indicator. Level ', NormalizeDouble(lv.Price_1(0), _int(SymbolInfoInteger(None, SYMBOL_DIGITS))), ' triggered!')
            if notification:
                SendNotification('Level Indicator. Level ' + _str(NormalizeDouble(lv.Price_1(0), _int(SymbolInfoInteger(None, SYMBOL_DIGITS)))) + ' triggered!')
        _s_OnCalculate_triggered = True
    else:
        _s_OnCalculate_triggered = False
    return rates_total

