def equal(_v1, _v2, _epsilon):
    return fabs(_v1 - _v2) <= fabs(_epsilon)

def OnInit():
    name = ""
    dv = 0.0
    color_ = 0
    name = 'alert.lv-'
    dv = deviation * SymbolInfoDouble(None, SYMBOL_POINT)
    color_ = (lineColor if (alert or notification) else inactivityColor)
    for n in range(0, INT_MAX + 1):
        if ObjectFind(0, name + _str(n)) != 0:
            if not lv.Create(0, name + _str(n), 0, trigLv):
                return INIT_FAILED
            lv.Width_1(lineWidth)
            lv.Style_1(lineStyle)
            lv.Color_1(color_)
            dvH.Create(0, 'alert.dvH-' + _str(n), 0, trigLv + dv)
            dvH.Width_1(1)
            dvH.Style_1(STYLE_DOT)
            dvH.Color_1(color_)
            dvL.Create(0, 'alert.dvL-' + _str(n), 0, trigLv - dv)
            dvL.Width_1(1)
            dvL.Style_1(STYLE_DOT)
            dvL.Color_1(color_)
            break
    if (not alert) and (not notification):
        Print('Level Indicator. Level ', lv.Price_1(0), ' is inactive!')
    if trigLv == 0.0:
        Alert('Level Indicator. Set parameter "trigLv" to the desired value!')
    return INIT_SUCCEEDED

