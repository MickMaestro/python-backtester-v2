CONSTS: dict[str, object] = {}
CONST_TYPES: dict[str, str] = {}
ENUMS: dict[str, dict[int, str]] = {}


def _enum(name: str, items: list[tuple[str, int]]):
    tbl = {}
    for k, v in items:
        CONSTS[k] = v
        CONST_TYPES[k] = "enum:" + name
        tbl.setdefault(v, k)
    ENUMS[name] = tbl


def _seq(name: str, names: str, start=0):
    _enum(name, [(n, start + i) for i, n in enumerate(names.split())])


